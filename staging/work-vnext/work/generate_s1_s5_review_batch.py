def d(u: str, a: str, f: str) -> list[dict[str, str]]:
    return [
        {"role": "user", "content": u},
        {"role": "assistant", "content": a},
        {"role": "user", "content": f},
    ]


def spec(uid, role, qt, pol, props, cx1, cx2, a, e1, b, e2, lure, bprime,
         query, target, calibrated, relation, nearby, why_not, why_d,
         a_elem, b_elem) -> dict[str, Any]:
    return {
        "uid": uid, "role": role, "query_type": QT[qt], "polarity": pol,
        "props": props, "cx1": cx1, "cx2": cx2, "a": a, "e1": e1, "b": b,
        "e2": e2, "lure": lure, "bprime": bprime, "query": query,
        "target": target, "calibrated": calibrated, "relation": relation,
        "nearby": nearby, "why_not": why_not, "why_distractor": why_d,
        "a_elem": a_elem, "b_elem": b_elem,
    }


