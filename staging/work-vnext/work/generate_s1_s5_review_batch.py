    if arm != "absence":
        ann["9"] = {"role": "supporting_constraint", "fact_id": "E1"}
        ann["17"] = {"role": "supporting_constraint", "fact_id": "E2"}
        a_ctx, a_goal, a_act, a_out = sp["a_elem"]
        b_ctx, b_goal, b_act, b_out = sp["b_elem"]
        ann["6"] = {"role": "ev_A", "event_elements": {
            "person": user_id, "context": a_ctx, "goal_or_prediction": a_goal,
            "action": a_act, "outcome_or_affect": a_out}}
