"""Work S1-S5 review batch, v2: 50 hand-authored sub-scenarios.

Design contract (see review/EXPERIMENTAL_DESIGN_AND_ARM_LOGIC.md):
- 5 scenario families x 10 profiles x 3 source conditions = 150 files.
- Every profile inside a scenario is a distinct sub-scenario: its own role,
  its own A and B episodes, its own E1/E2 calibration facts, its own
  counterexamples, its own query angle, its own B-prime and distractor.
- Core logic per item: A alone does not support C; B alone does not support C;
  A+B support C; B-prime breaks the relation; absence withholds the episodes.
- Query-type quota over the 50 base units:
  preference_generalization 8, situational_fit 8, recommendation_ranking 8,
  predicted_reaction 8, behavior_explanation 9, conditional_recommendation 9.
- Polarity quota: accept 15, reject 20, conditional 10, non_decision 5.
- Admission gate: deterministic score >= 95 AND batch-level uniqueness/quota
  audit must pass before any file is written.
"""

