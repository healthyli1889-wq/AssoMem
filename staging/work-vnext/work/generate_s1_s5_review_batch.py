# session slot layout (session_id -> content source)
# 1 bg0, 2 bg1, 3 cx1, 4 bg2, 5 bg3, 6 A, 7 cx2, 8 bg4, 9 E1, 10 bg5,
# 11 bg6, 12 bg7, 13 bg8, 14 B, 15 bg9, 16 bg10, 17 E2, 18 bg11(lure in distractor), 19 bg12, 20 query
SLOT_BG = {1: 0, 2: 1, 4: 2, 5: 3, 8: 4, 10: 5, 11: 6, 12: 7, 13: 8, 15: 9, 16: 10, 18: 11, 19: 12}
HOURS = [9, 11, 14, 16, 18]


def fill(template: tuple[str, str, str], props: tuple[str, str, str, str]) -> list[dict[str, str]]:
    keys = {"artifact": props[0], "task": props[1], "place": props[2], "focus": props[3]}
    return d(*(part.format(**keys) for part in template))


def build_context(sp: dict[str, Any], s_idx: int, u_idx: int, user_id: str) -> list[dict[str, Any]]:
    base = datetime(2026, 3, 2, tzinfo=timezone.utc) + timedelta(days=s_idx * 45 + u_idx * 2)
    sessions = []
    for sid in range(1, 21):
        if sid in SLOT_BG:
            dialogue = fill(BG[SLOT_BG[sid]], sp["props"])
        elif sid == 3:
            dialogue = sp["cx1"]
        elif sid == 6:
            dialogue = sp["a"]
        elif sid == 7:
            dialogue = sp["cx2"]
        elif sid == 9:
            dialogue = sp["e1"]
        elif sid == 14:
            dialogue = sp["b"]
        elif sid == 17:
            dialogue = sp["e2"]
        else:  # 20
            dialogue = [{"role": "user", "content": sp["query"]}]
        ts = base + timedelta(days=sid - 1, hours=HOURS[sid % len(HOURS)])
        sessions.append({
            "session_id": sid,
            "timestamp": ts.strftime("%Y-%m-%dT%H:%M:00Z"),
            "speaker_id": user_id,
            "speaker_label": "User",
            "dialogue": [dict(t) for t in dialogue],
        })
    return sessions


def neutral(text_u: str, text_a: str, text_f: str) -> list[dict[str, str]]:
    return d(text_u, text_a, text_f)


def annotate(sp: dict[str, Any], user_id: str, arm: str) -> dict[str, Any]:
    ann: dict[str, Any] = {str(i): {"role": "background_memory"} for i in range(1, 21)}
    ann["3"] = {"role": "nearby_counterexample"}
