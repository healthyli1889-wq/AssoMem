META_PHRASES = ("target relation", "latent c", "this proves", "the conclusion is")


def score_item(item: dict[str, Any]) -> tuple[int, list[str]]:
    total, notes = 0, []
    ctx = item["context"]
    if len(ctx) == 20 and len({s["session_id"] for s in ctx}) == 20:
        total += 20
    else:
        notes.append("not exactly 20 unique sessions")
    if [s["timestamp"] for s in ctx] == sorted(s["timestamp"] for s in ctx):
        total += 10
    else:
        notes.append("timestamps not monotonic")
    if all(t["content"].strip().endswith((".", "?", "!")) for s in ctx for t in s["dialogue"]):
        total += 15
    else:
        notes.append("incomplete sentence punctuation")
    visible = " ".join(t["content"].lower() for s in ctx for t in s["dialogue"])
    if not any(p in visible for p in META_PHRASES):
        total += 15
    else:
        notes.append("meta-language leaked")
    if item["data_arm"] != "absence" and set(item["evidence"]) == {"ev_A", "ev_B"}:
        total += 15
    elif item["data_arm"] == "absence" and item.get("target_evidence_ids") == []:
        total += 15
    else:
        notes.append("evidence/absence contract failed")
    if item["data_arm"] == "associative" and {"a_only", "b_only", "link_broken"} <= set(item["arm_gold"]):
        total += 15
    elif item["data_arm"] != "associative":
        total += 15
    else:
        notes.append("core controls missing")
    if item["provenance"].get("persona_anchor", "").startswith("work_u"):
        total += 10
    else:
        notes.append("persona anchor missing")
    if item["latent_C"]["inference"].lower() in visible or item["latent_C"]["inference"].lower() in item["query"].lower():
        total = 0
        notes.append("latent C leaked verbatim")
    return total, notes


def batch_audit(all_specs: dict[str, list[dict[str, Any]]]) -> list[str]:
    problems: list[str] = []
    qt_counts: dict[str, int] = {}
    pol_counts: dict[str, int] = {}
    seen_a, seen_b, seen_q = set(), set(), set()
    for sid, specs in all_specs.items():
        for sp in specs:
            qt_counts[sp["query_type"]] = qt_counts.get(sp["query_type"], 0) + 1
            pol_counts[sp["polarity"]] = pol_counts.get(sp["polarity"], 0) + 1
            a_txt, b_txt, q_txt = sp["a"][0]["content"], sp["b"][0]["content"], sp["query"]
            for label, text, seen in (("A", a_txt, seen_a), ("B", b_txt, seen_b), ("query", q_txt, seen_q)):
                if text in seen:
                    problems.append(f"duplicate {label} text in {sid}/{sp['uid']}")
                seen.add(text)
    expected_qt = {
        "preference_generalization": 8, "situational_fit": 8,
        "recommendation_ranking": 8, "predicted_reaction": 8,
        "behavior_explanation": 9, "conditional_recommendation": 9,
    }
    if qt_counts != expected_qt:
        problems.append(f"query-type quota mismatch: {qt_counts}")
    expected_pol = {"accept": 15, "reject": 20, "conditional": 10, "non_decision": 5}
    if pol_counts != expected_pol:
        problems.append(f"polarity quota mismatch: {pol_counts}")
    return problems


def main() -> int:
    problems = batch_audit(SCENARIOS)
    if problems:
        print("BATCH AUDIT FAILED; nothing written:")
        for p in problems:
            print(" -", p)
        return 1

    for arm in ("associative", "distractor", "absence"):
        (OUT / arm).mkdir(parents=True, exist_ok=True)

    audit: list[dict[str, Any]] = []
    written = 0
    for s_idx, (sid, specs) in enumerate(SCENARIOS.items()):
        for u_idx, sp in enumerate(specs):
            for arm in ("associative", "distractor", "absence"):
                item = build_item(sid, s_idx, sp, u_idx, arm)
                total, notes = score_item(item)
                record = {
                    "candidate_id": item["candidate_id"], "scenario": sid,
                    "profile": sp["uid"], "role": sp["role"], "arm": arm,
                    "query_type": sp["query_type"], "polarity": sp["polarity"],
                    "score": total, "passed": total >= 95, "notes": notes,
                }
                audit.append(record)
                if total >= 95:
                    path = OUT / arm / f"{item['candidate_id']}.json"
                    path.write_text(json.dumps(item, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
                    written += 1
                else:
                    print(f"REJECTED {item['candidate_id']} score={total} notes={notes}")

    AUDIT_PATH.parent.mkdir(parents=True, exist_ok=True)
    AUDIT_PATH.write_text(json.dumps(audit, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    passed = sum(1 for r in audit if r["passed"])
    print(f"PASS {passed}/{len(audit)}; written={written}; out={OUT}")
    print(f"AUDIT {AUDIT_PATH}")
    return 0 if passed == len(audit) else 1


