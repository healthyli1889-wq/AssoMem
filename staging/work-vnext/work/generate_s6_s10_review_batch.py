# Timestamps: keep all sessions in the past (Aug 2025 - Feb 2026), before the
# S1-S5 batch window, so the two batches never share a timestamp.
def build_context(sp: dict[str, Any], s_idx: int, u_idx: int, user_id: str) -> list[dict[str, Any]]:
    base_dt = datetime(2025, 8, 4, tzinfo=timezone.utc) + timedelta(days=s_idx * 40 + u_idx * 2)
    sessions = []
    for sid in range(1, 21):
        if sid in base.SLOT_BG:
            dialogue = base.fill(base.BG[base.SLOT_BG[sid]], sp["props"])
        elif sid == 3:
            dialogue = sp["cx1"]
        elif sid == 6:
            dialogue = sp["a"]
        elif sid == 7:
            dialogue = sp["cx2"]
        elif sid == 9:
            dialogue = sp["e1"]
        elif sid == 14:
            dialogue = sp["b"]
        elif sid == 17:
            dialogue = sp["e2"]
        else:
            dialogue = [{"role": "user", "content": sp["query"]}]
        ts = base_dt + timedelta(days=sid - 1, hours=base.HOURS[sid % len(base.HOURS)])
        sessions.append({
            "session_id": sid,
            "timestamp": ts.strftime("%Y-%m-%dT%H:%M:00Z"),
            "speaker_id": user_id,
            "speaker_label": "User",
            "dialogue": [dict(t) for t in dialogue],
        })
    return sessions


