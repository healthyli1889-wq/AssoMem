def cross_batch_uniqueness() -> list[str]:
    problems: list[str] = []
    old_texts: set[str] = set()
    for specs in base.SCENARIOS.values():
        for sp in specs:
            old_texts.add(sp["a"][0]["content"])
            old_texts.add(sp["b"][0]["content"])
            old_texts.add(sp["query"])
    for sid, specs in SCENARIOS.items():
        for sp in specs:
            for label, text in (("A", sp["a"][0]["content"]), ("B", sp["b"][0]["content"]), ("query", sp["query"])):
                if text in old_texts:
                    problems.append(f"{sid}/{sp['uid']} {label} text repeats S1-S5")
    return problems


def main() -> int:
    problems = base.batch_audit(SCENARIOS) + cross_batch_uniqueness()
    if problems:
        print("BATCH AUDIT FAILED; nothing written:")
        for p in problems:
            print(" -", p)
        return 1

    base.FAMILY.update(FAMILY)
    base.build_context = build_context  # past-dated window, disjoint from S1-S5

    for arm in ("associative", "distractor", "absence"):
        (OUT / arm).mkdir(parents=True, exist_ok=True)

    audit: list[dict[str, Any]] = []
    written = 0
    for s_idx, (sid, specs) in enumerate(SCENARIOS.items()):
        for u_idx, sp in enumerate(specs):
            for arm in ("associative", "distractor", "absence"):
                item = base.build_item(sid, s_idx, sp, u_idx, arm)
                total, notes = base.score_item(item)
                audit.append({
                    "candidate_id": item["candidate_id"], "scenario": sid,
                    "profile": sp["uid"], "role": sp["role"], "arm": arm,
                    "query_type": sp["query_type"], "polarity": sp["polarity"],
                    "score": total, "passed": total >= 95, "notes": notes,
                })
                if total >= 95:
                    path = OUT / arm / f"{item['candidate_id']}.json"
                    path.write_text(json.dumps(item, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
                    written += 1
                else:
                    print(f"REJECTED {item['candidate_id']} score={total} notes={notes}")

    AUDIT_PATH.parent.mkdir(parents=True, exist_ok=True)
    AUDIT_PATH.write_text(json.dumps(audit, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    passed = sum(1 for r in audit if r["passed"])
    print(f"PASS {passed}/{len(audit)}; written={written}; out={OUT}")
    print(f"AUDIT {AUDIT_PATH}")
    return 0 if passed == len(audit) else 1


